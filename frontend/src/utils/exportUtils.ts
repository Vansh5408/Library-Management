export function exportBorrowRecordsToCSV(records: any[]) {
  const exportData = records.map(record => ({
    'User Name': record.user?.name || 'Unknown',
    'User Email': record.user?.email || 'N/A',
    'Book Title': record.book?.title || 'Unknown',
    'Book Author': record.book?.author || 'N/A',
    'Borrowed Date': new Date(record.borrowedAt).toLocaleDateString(),
    'Due Date': new Date(record.dueDate).toLocaleDateString(),
    'Returned Date': record.returnedAt ? new Date(record.returnedAt).toLocaleDateString() : 'Not Returned',
    'Status': record.status,
    'Fine Amount': record.fineAmount ? `$${record.fineAmount}` : '$0',
    'Fine Paid': record.finePaid ? 'Yes' : 'No',
  }));

  exportToCSV(exportData, 'borrow_records');
}

export function exportBooksToCSV(books: any[]) {
  const exportData = books.map(book => ({
    'Title': book.title,
    'Author': book.author,
    'ISBN': book.isbn,
    'Description': book.description,
    'Total Copies': book.totalCopies,
    'Available Copies': book.availableCopies,
    'Borrowed Copies': book.totalCopies - book.availableCopies,
    'Created At': new Date(book.createdAt).toLocaleDateString(),
  }));

  exportToCSV(exportData, 'books_inventory');
}

