// Generate PDF content for borrow records
export function exportBorrowRecordsToPDF(records: any[], stats?: any) {
  const statsHtml = stats ? `
    <div class="stat-grid">
      <div class="stat-card">
        <div class="label">Total Records</div>
        <div class="value">${records.length}</div>
      </div>
      <div class="stat-card">
        <div class="label">Active Borrows</div>
        <div class="value">${records.filter(r => r.status === 'active').length}</div>
      </div>
      <div class="stat-card">
        <div class="label">Overdue</div>
        <div class="value">${records.filter(r => r.status === 'overdue').length}</div>
      </div>
    </div>
  ` : '';

  const tableRows = records.map(record => `
    <tr>
      <td>${record.user?.name || 'Unknown'}</td>
      <td>${record.book?.title || 'Unknown'}</td>
      <td>${new Date(record.borrowedAt).toLocaleDateString()}</td>
      <td>${new Date(record.dueDate).toLocaleDateString()}</td>
      <td>${record.returnedAt ? new Date(record.returnedAt).toLocaleDateString() : '-'}</td>
      <td class="status-${record.status}">${record.status.toUpperCase()}</td>
      <td class="${record.finePaid ? 'fine-paid' : 'fine-unpaid'}">
        ${record.fineAmount ? '$' + record.fineAmount + (record.finePaid ? ' ✓' : '') : '-'}
      </td>
    </tr>
  `).join('');

  const content = `
    <div class="header">
      <h1>📚 Library Borrow Records Report</h1>
      <p class="date">Generated on ${new Date().toLocaleDateString()}</p>
    </div>
    ${statsHtml}
    <div class="section">
      <h2>Borrow Records</h2>
      <table>
        <thead>
          <tr>
            <th>User</th>
            <th>Book</th>
            <th>Borrowed</th>
            <th>Due Date</th>
            <th>Returned</th>
            <th>Status</th>
            <th>Fine</th>
          </tr>
        </thead>
        <tbody>
          ${tableRows}
        </tbody>
      </table>
    </div>
  `;

  exportToPDF('Borrow Records Report', content, 'borrow_records');
}

// Generate PDF content for books inventory
